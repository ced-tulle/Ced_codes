// Simple Student Program

// 3 Variables
let name = "John";
let age = 20;
let score = 80;

// 3 Arrays
let fruits = ["Apple", "Banana", "Mango"];
let numbers = [1, 2, 3];
let grades = [80, 75, 90];

// 3 Loops

// Loop 1
for (let i = 0; i < fruits.length; i++) {
    console.log(fruits[i]);
}

// Loop 2
for (let i = 0; i < numbers.length; i++) {
    console.log(numbers[i]);
}

// Loop 3
for (let i = 0; i < grades.length; i++) {
    console.log(grades[i]);
}

// 3 Conditionals

// Conditional 1
if (score >= 75) {
    console.log("Passed");
}

// Conditional 2
if (age >= 18) {
    console.log("Adult");
}

// Conditional 3
if (score >= 90) {
    console.log("Excellent");
} else {
    console.log("Good");
}